export function normalizeLanguageTag(value) {
  const code = typeof value === 'string' ? value.trim().toLowerCase().split(/[-_]/)[0] : '';
  return code === 'nl' ? 'nl' : 'en';
}

// HA user language first if same-origin parent exposes it, else browser locale.
// Parent access may be disallowed by iframe origin rules; don't throw.
export function detectLanguage(parentWindow, browserNavigator) {
  try {
    const ha = parentWindow?.document?.querySelector('home-assistant');
    const hass = ha?.hass;
    const selected = hass?.locale?.language || hass?.language || hass?.user?.language;
    if (typeof selected === 'string' && selected.trim()) return normalizeLanguageTag(selected);
  } catch { /* Cross-origin frame; browser fallback */ }
  const languages = browserNavigator?.languages;
  const choice = (Array.isArray(languages) && languages.length ? languages[0] : null)
    || browserNavigator?.language || 'en';
  return normalizeLanguageTag(choice);
}

// Explicit add-on setting takes precedence over the current HA/browser locale.
export function resolveLanguage(preference, parentWindow, browserNavigator) {
  if (preference === 'en' || preference === 'nl') return preference;
  return detectLanguage(parentWindow, browserNavigator);
}

export function t(language, key, values = {}) {
  const pattern = (messages[language] || messages.en)[key] ?? messages.en[key];
  if (pattern === undefined) throw new Error(`Missing translation: ${key}`);
  return pattern.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}

export function translateStatic(root, language) {
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(language, el.dataset.i18n);
  });
  for (const [datasetKey, attribute] of [
    ['i18nAria', 'aria-label'], ['i18nTitle', 'title'],
    ['i18nPlaceholder', 'placeholder'], ['i18nContent', 'content']
  ]) {
    root.querySelectorAll(`[data-${datasetKey.replace(/([A-Z])/g, '-$1').toLowerCase()}]`).forEach(el => {
      el.setAttribute(attribute, t(language, el.dataset[datasetKey]));
    });
  }
}
